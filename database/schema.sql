CREATE VIEW public.ns_project_financial_summary AS
 WITH contract_totals AS (
         SELECT ns_contract.project_id,
            sum(ns_contract.amount) AS contracted_amount
           FROM public.ns_contract
          WHERE ((ns_contract.status)::text <> ALL ((ARRAY['draft'::character varying, 'terminated'::character varying])::text[]))
          GROUP BY ns_contract.project_id
        ), payment_totals AS (
         SELECT c_1.project_id,
            sum(p_1.amount) FILTER (WHERE ((p_1.status)::text = 'paid'::text)) AS paid_amount,
            sum(p_1.amount) FILTER (WHERE ((p_1.status)::text = 'approved'::text)) AS approved_unpaid_amount
           FROM (((public.ns_payment p_1
             JOIN public.ns_inspection i ON ((i.id = p_1.inspection_id)))
             JOIN public.ns_milestone m ON ((m.id = i.milestone_id)))
             JOIN public.ns_contract c_1 ON ((c_1.id = m.contract_id)))
          GROUP BY c_1.project_id
        )
 SELECT p.id AS project_id,
    p.code,
    p.name,
    p.sanctioned_budget,
    COALESCE(c.contracted_amount, (0)::numeric) AS contracted_amount,
    COALESCE(t.paid_amount, (0)::numeric) AS paid_amount,
    COALESCE(t.approved_unpaid_amount, (0)::numeric) AS approved_unpaid_amount,
    (p.sanctioned_budget - COALESCE(t.paid_amount, (0)::numeric)) AS remaining_budget
   FROM ((public.ns_project p
     LEFT JOIN contract_totals c ON ((c.project_id = p.id)))
     LEFT JOIN payment_totals t ON ((t.project_id = p.id)));


